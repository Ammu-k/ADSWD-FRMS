export function initLang() {
    try {
        currentLang = localStorage.getItem(STORAGE_KEY) || 'en';
    } catch (e) {
        currentLang = 'en';
    }
    return currentLang;
}

export function getLang() { return currentLang; }

export function t(key) {
    const lang = translations[currentLang] || translations.en;
    return lang[key] || translations.en[key] || key;
}

export function setLanguage(lang) {
    currentLang = lang;
    localStorage.setItem(STORAGE_KEY, lang);
    const dict = translations[lang] || translations.en;
    document.querySelectorAll('[data-i18n]').forEach(el => {
        const key = el.getAttribute('data-i18n');
        if (dict[key]) {
            if (el.querySelector('input,select')) {
                for (let n of el.childNodes) { if (n.nodeType === 3) { n.textContent = dict[key]; break; } }
            } else { el.textContent = dict[key]; }
        }
    });
    document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
        const key = el.getAttribute('data-i18n-placeholder');
        if (dict[key]) el.placeholder = dict[key];
    });
    document.documentElement.lang = lang === 'kn' ? 'kn' : lang === 'hi' ? 'hi' : 'en';
    document.querySelectorAll('.lang-option').forEach(o => {
        o.style.borderColor = o.dataset.lang === lang ? 'var(--primary)' : 'var(--border)';
        o.style.background = o.dataset.lang === lang ? 'rgba(30,58,95,.05)' : '';
    });
}

